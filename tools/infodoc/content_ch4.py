def topic_catalog(section_key, number):
    """ساخت خودکار بخش کاتالوگ موضوع‌های یک محور از دادهٔ واقعی برنامه."""
    blocks = []
    items = [t for t in TOPICS if t["section"] == section_key]
    for i, topic in enumerate(items, 1):
        extra = EXTRAS.get(topic["id"], {})
        blocks.append(("h3", f"{number}-{fa(i)}  {topic['title']}"))
        blocks.append(("p", topic["summary"]))
        blocks.append(("img", {
            "path": "Assets/Images/" + topic["image"],
            "height": 52,
            "width": 122,
            "caption": "تصویر موضوع «" + topic["title"] + "» در برنامه",
        }))
        if topic["bullets"]:
            blocks.append(("h4", "نکات کلیدی طراحی که در برنامه نمایش داده می‌شود"))
            blocks.append(("ul", topic["bullets"]))
        specs = extra.get("specs", [])
        if specs:
            blocks.append(("tbl", {
                "caption": f"مشخصات فنی موضوع «{topic['title']}» (در برگهٔ {topic['id']}.pdf)",
                "headers": ["شاخص", "مقدار"],
                "widths": [40, 60],
                "rows": [[k, v] for k, v in specs],
            }))
        if extra.get("energyNote"):
            blocks.append(("note", {
                "kind": "green",
                "title": "نکتهٔ بهره‌وری انرژی این موضوع",
                "text": extra["energyNote"],
            }))
        if extra.get("keywords"):
            blocks.append(("p", "واژگان کلیدی: " + extra["keywords"] + "."))
    return blocks


